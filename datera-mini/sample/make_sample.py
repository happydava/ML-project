"""Builds a small test pair: sample/slides.pptx and sample/talk.m4a (macOS `say`)."""
import subprocess
from pathlib import Path
from pptx import Presentation

here = Path(__file__).parent
slides = [
    ("Нейронные сети", ["Вводная лекция"]),
    ("Что такое нейронная сеть", [
        "Нейронная сеть состоит из слоёв искусственных нейронов",
        "Каждый нейрон считает взвешенную сумму входов и применяет функцию активации",
        "Сеть учится на примерах, а не по заданным вручную правилам"]),
    ("Обучение сети", [
        "Функция потерь показывает, насколько сильно ошибается модель",
        "Градиентный спуск шаг за шагом уменьшает ошибку",
        "Обратное распространение ошибки вычисляет градиенты для всех весов"]),
    ("Переобучение", [
        "Модель запоминает обучающие данные и плохо работает на новых",
        "Dropout случайно отключает часть нейронов во время обучения",
        "Ранняя остановка по качеству на валидационной выборке"]),
    ("Свёрточные сети", [
        "Свёртка ищет локальные признаки на изображении",
        "Пулинг уменьшает размер карты признаков",
        "Перенос обучения использует готовую сеть VGG16"]),
]
prs = Presentation()
for i, (title, points) in enumerate(slides):
    s = prs.slides.add_slide(prs.slide_layouts[0 if i == 0 else 1])
    s.shapes.title.text = title
    body = s.placeholders[1].text_frame
    body.text = points[0]
    for p in points[1:]:
        body.add_paragraph().text = p
prs.save(here / "slides.pptx")

talk = """
Здравствуйте. Сегодня мы поговорим о нейронных сетях.
Нейронная сеть состоит из слоёв, и в каждом слое находятся искусственные нейроны.
Каждый нейрон складывает свои входы с весами и пропускает результат через функцию активации.
Главное отличие от обычных программ в том, что сеть учится на примерах, а правила вручную никто не пишет.
Теперь об обучении. Чтобы понять, насколько модель ошибается, используют функцию потерь.
Градиентный спуск постепенно, шаг за шагом, уменьшает эту ошибку.
А градиенты для всех весов считает алгоритм обратного распространения ошибки.
Кстати, вчера я ездил на рыбалку на озеро, поймал двух больших щук и потом долго жарил их на костре вместе с друзьями.
Вернёмся к теме. Есть проблема переобучения: модель запоминает обучающие данные и плохо работает на новых данных.
Один из способов борьбы называется дропаут, он случайно отключает часть нейронов во время обучения.
На этом на сегодня всё, спасибо за внимание.
"""
(here / "talk.txt").write_text(talk, encoding="utf-8")
subprocess.run(["say", "-v", "Milena", "-f", str(here / "talk.txt"), "-o", str(here / "talk.aiff")], check=True)
subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(here / "talk.aiff"), str(here / "talk.m4a")], check=True)
(here / "talk.aiff").unlink()
print("ok")
